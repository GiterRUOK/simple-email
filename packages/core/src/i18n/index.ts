const FALLBACK_LOCALE: SimpleMailLocale = 'zh-CN';

export function createI18nContext(options: SimpleMailI18nOptions = {}): SimpleMailI18nContext {
  const locale = options.locale ?? FALLBACK_LOCALE;
  const base = locale === 'en-US' ? enUSMessages : zhCNMessages;
  const messages: SimpleMailMessages = { ...zhCNMessages, ...base };
  for (const [key, value] of Object.entries(options.messages ?? {})) {
    if (typeof value === 'string') messages[key] = value;
  }
  const t: SimpleMailT = (key, params) => {
    let text = messages[key] ?? zhCNMessages[key] ?? key;
    if (params) {
      for (const [name, value] of Object.entries(params)) {
        text = text.replaceAll(`{${name}}`, String(value));
      }
    }
    return text;
  };
  return { locale, messages, t };
}
